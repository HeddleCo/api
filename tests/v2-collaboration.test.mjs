test('signed malformed turn bodies and root/non-root frontiers cannot become parents', async () => {
  async function signMutated(mutate) {
    const record = structuredClone(fixtures.open.record);
    const outer = decode(record.canonicalRecord);
    const inner = decode(Uint8Array.from(outer.body.canonical));
    mutate(inner);
    outer.body.canonical = Array.from(encode(inner));
    record.canonicalRecord = encode(outer);
    record.signatures[0].signature = await signer.sign(Buffer.concat([Buffer.from('heddle-thread-operation-v1\0'), record.canonicalRecord]));
    return record;
  }
  await assert.rejects(verifyCollaboration(await signMutated(inner => { inner.body.turn.body = 'Changed without matching content hash'; })), /content hash/);
  await assert.rejects(verifyCollaboration(await signMutated(inner => { inner.body = { kind: 'append_turn', turn: inner.body.turn }; })), /empty causal frontier/);
  await assert.rejects(signDiscussion(openCommand, [fixtures.open.record], signer), /empty causal frontier/);
  await assert.rejects(signDiscussion(command({ kind: 'append', body: 'Reply' }), [], signer), /empty causal frontier/);
});

