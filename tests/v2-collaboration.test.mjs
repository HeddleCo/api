// Both SDKs consume these exact target IDs; Rust derives its copies from model cores.
test('shared source target interning preserves identity across materialized locations', () => {
  const source = create(SourceAnchorSchema, {
    revision: { spool: { id: '00000000-0000-0000-0000-000000000001' }, revision: { case: 'state', value: { value: new Uint8Array(32).fill(5) } } },
    thread: { spool: { id: '00000000-0000-0000-0000-000000000001' }, id: { value: new Uint8Array(32).fill(2) } }, path: 'src/main.rs',
  });
  const binding = { case: 'viewedThread', value: true };
  const vectors = JSON.parse(readFileSync(new URL('./fixtures/source-target-ids.json', import.meta.url), 'utf8'));
  for (const [kind, fields] of [['file', {}], ['lines', { startLine: 12, endLine: 18 }], ['symbol', { symbolId: 'main::run' }]]) {
    const original = create(SourceAnchorSchema, { ...source, ...fields });
    const target = sourceTargetReference(original, binding);
    assert.equal(Buffer.from(target.targetId).toString('hex'), vectors[kind]);
    const moved = create(SourceAnchorSchema, { ...original, path: 'renamed.rs', startLine: 20, endLine: 25, target });
    const pinned = { case: 'pinnedRevision', value: { revision: original.revision, thread: original.thread } };
    assert.deepEqual(sourceTargetReference(moved, pinned).targetId, target.targetId);
    assert.equal(moved.target.binding.case, 'viewedThread', 'helper does not mutate existing binding');
  }
  assert.throws(() => sourceTargetReference(create(SourceAnchorSchema, { ...source, startLine: 0, endLine: 2 }), binding));
  assert.throws(() => sourceTargetReference(source, { case: 'viewedThread', value: false }));
});
