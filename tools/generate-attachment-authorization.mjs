import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = readFileSync("proto/heddle/api/v1alpha1/repo_sync.proto", "utf8");
const enumStart = source.indexOf("enum StateAttachmentKind {");
if (enumStart < 0) throw new Error("missing StateAttachmentKind");

let depth = 0;
let enumEnd = -1;
for (let index = source.indexOf("{", enumStart); index < source.length; index += 1) {
  if (source[index] === "{") depth += 1;
  if (source[index] === "}") depth -= 1;
  if (depth === 0) {
    enumEnd = index;
    break;
  }
}
if (enumEnd < 0) throw new Error("unterminated StateAttachmentKind");

const body = source.slice(enumStart, enumEnd + 1);
const entry = /^\s*(STATE_ATTACHMENT_KIND_[A-Z0-9_]+)\s*=\s*(\d+)\s*(\[[\s\S]*?\])?\s*;/gm;
const rows = [];
for (const match of body.matchAll(entry)) {
  const [, name, numberText, options = ""] = match;
  const number = Number(numberText);
  if (number === 0) continue;
  const classification = options.match(
    /STATE_ATTACHMENT_AUTHORIZATION_CLASSIFICATION_([A-Z0-9_]+)/,
  )?.[1];
  if (!classification || classification === "UNSPECIFIED") {
    throw new Error(
      `${name} is missing a non-UNSPECIFIED state_attachment_authorization_classification`,
    );
  }
  const classificationNumber = {
    NOT_AUTHORITATIVE: 1,
    METADATA_SUPERSESSION: 2,
  }[classification];
  if (classificationNumber === undefined) {
    throw new Error(`${name} has unknown classification ${classification}`);
  }
  rows.push({ name, number, classification, classificationNumber });
}
if (rows.length === 0) throw new Error("StateAttachmentKind has no classified values");

const output = `// Generated by tools/generate-attachment-authorization.mjs.\n` +
  `export const STATE_ATTACHMENT_AUTHORIZATION_CONFORMANCE = ${JSON.stringify(rows, null, 2)} as const;\n\n` +
  `export function stateAttachmentAuthorizationClassification(kind: number): number | undefined {\n` +
  `  return STATE_ATTACHMENT_AUTHORIZATION_CONFORMANCE.find((entry) => entry.number === kind)?.classificationNumber;\n` +
  `}\n`;
writeFileSync(
  join("build", "typescript", "heddle", "api", "v1alpha1", "attachment-authorization.ts"),
  output,
);
